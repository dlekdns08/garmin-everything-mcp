#!/usr/bin/env python
"""Regenerate docs/COVERAGE.md: every garminconnect.Garmin method x
{garmin_mcp, this server (extras / all / full), group, read/write}.

    uv run python scripts/gen_coverage.py          # writes docs/COVERAGE.md
    uv run python scripts/gen_coverage.py --badge  # prints the one-line summary
"""

from __future__ import annotations

import sys
from importlib import metadata
from pathlib import Path

from garminconnect import Garmin

from garmin_everything_mcp import registry

DOCS = Path(__file__).resolve().parent.parent / "docs" / "COVERAGE.md"


def compute(cls: type = Garmin) -> dict:
    infos = registry.introspect(cls)
    specs = registry.build_specs(cls, infos)
    wrapped = registry.garmin_mcp_wrapped()
    foreign = registry.garmin_mcp_tool_names()
    sel = {
        "extras": {s.name for s in registry.select_tools(specs, "extras", wrapped=wrapped, foreign_tool_names=foreign).selected},
        "all": {s.name for s in registry.select_tools(specs, "all", wrapped=wrapped, foreign_tool_names=foreign).selected},
        "full": {s.name for s in registry.select_tools(specs, "full", writes_enabled=True, wrapped=wrapped, foreign_tool_names=foreign).selected},
    }
    rows = []
    for name, info in infos.items():
        rows.append({
            "method": name, "group": info.group, "kind": info.kind,
            "garmin_mcp": name in wrapped or name in foreign,
            "extras": name in sel["extras"], "all": name in sel["all"], "full": name in sel["full"],
            "skip": info.skip_reason or "",
        })
    try:
        version = metadata.version("garminconnect")
    except metadata.PackageNotFoundError:
        version = "unknown"
    return {"version": version, "rows": rows, "wrapped_total": len(wrapped),
            "wrapped_in_lib": len(wrapped & set(infos)), "sel": sel,
            "read": sum(1 for i in infos.values() if i.kind == "read"),
            "write": sum(1 for i in infos.values() if i.kind == "write")}


def badge_line(c: dict) -> str:
    n = len(c["rows"])
    covered = sum(1 for r in c["rows"] if r["garmin_mcp"])
    return (f"garminconnect {c['version']}: {n} methods | garmin_mcp covers {covered} | "
            f"garmin-everything-mcp adds {len(c['sel']['extras'])} (extras) / {len(c['sel']['all'])} (all) / "
            f"{len(c['sel']['full'])} (full) auto-generated tools + 8 hand-written")


def render(c: dict) -> str:
    rows = c["rows"]
    n = len(rows)
    covered = sum(1 for r in rows if r["garmin_mcp"])
    y = lambda b: "yes" if b else ""  # noqa: E731
    groups: dict[str, dict[str, int]] = {}
    for r in rows:
        g = groups.setdefault(r["group"], {"methods": 0, "garmin_mcp": 0, "extras": 0, "all": 0, "full": 0})
        g["methods"] += 1
        for k in ("garmin_mcp", "extras", "all", "full"):
            g[k] += int(r[k])
    out = [
        "# Coverage matrix",
        "",
        "Generated by `scripts/gen_coverage.py`. Do not edit by hand.",
        "",
        f"**{badge_line(c)}**",
        "",
        f"- Library: `garminconnect=={c['version']}`, {n} public methods ({c['read']} read, {c['write']} write).",
        f"- `garmin_mcp` wraps {c['wrapped_total']} client calls, {c['wrapped_in_lib']} of which are `Garmin` methods in this version; "
        f"together with tool names that shadow library methods it covers {covered} of {n}.",
        f"- Profile `extras` (default): {len(c['sel']['extras'])} read tools that garmin_mcp does not provide.",
        f"- Profile `all`: {len(c['sel']['all'])} read tools (every read method, duplicates garmin_mcp names).",
        f"- Profile `full`: {len(c['sel']['full'])} tools including {len(c['sel']['full']) - len(c['sel']['all'])} write methods (needs `GARMIN_EVERYTHING_WRITES=1`).",
        f"- Skipped on purpose: {sum(1 for r in rows if r['skip'])} (session/raw/clock helpers; bytes methods are wrapped by overrides).",
        "",
        "## By group",
        "",
        "| group | methods | garmin_mcp | extras | all | full |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for g, v in sorted(groups.items()):
        out.append(f"| {g} | {v['methods']} | {v['garmin_mcp']} | {v['extras']} | {v['all']} | {v['full']} |")
    out += ["", "## All methods", "", "| method | group | kind | garmin_mcp | extras | all | full | note |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| `{r['method']}` | {r['group']} | {r['kind']} | {y(r['garmin_mcp'])} | {y(r['extras'])} | {y(r['all'])} | {y(r['full'])} | {r['skip']} |")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> None:
    c = compute()
    if "--badge" in argv:
        print(badge_line(c))
        return
    DOCS.parent.mkdir(parents=True, exist_ok=True)
    DOCS.write_text(render(c))
    print(f"wrote {DOCS}", file=sys.stderr)
    print(badge_line(c))


if __name__ == "__main__":
    main(sys.argv[1:])
